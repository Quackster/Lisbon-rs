/// Mirrors the Java `Font` glyph lookup (uppercase falls back to lowercase).
pub fn glyph(character: char) -> Option<Glyph> {
    FONT.iter()
        .find(|(name, _)| *name == character.to_ascii_lowercase().to_string())
        .map(|(_, glyph)| *glyph)
}

/// Yields the `(column, row)` of every set pixel of the glyph.
pub fn set_pixels(glyph: Glyph) -> impl Iterator<Item = (usize, usize)> {
    (0..7).flat_map(move |row| {
        (0..5)
            .filter(move |column| (glyph[row] >> (4 - column)) & 1 != 0)
            .map(move |column| (column, row))
    })
}
